export type Locale = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;
type Slots<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | Slots<Rest> : never;
export type TranslationArgs<K extends MessageKey> = [Slots<(typeof messages.en)[K]>] extends [never]
  ? [params?: Record<string, never>] : [params: Record<Slots<(typeof messages.en)[K]>, string | number>];
// Compile-time key and placeholder parity, without widening the literal dictionaries.
type Equal<A, B> = [A] extends [B] ? [B] extends [A] ? true : false : false;
type Assert<T extends true> = T;
type KeyParity = Assert<Equal<keyof typeof messages.en, keyof typeof messages['zh-CN']>>;
type PlaceholderParity = Assert<{ [K in MessageKey]: Equal<Slots<(typeof messages.en)[K]>, Slots<(typeof messages['zh-CN'])[K]>> }[MessageKey]>;
let locale: Locale = 'zh-CN';
export function getLocale(): Locale { return locale; }
export function setLocale(value: unknown): boolean {
  const normalized = typeof value === 'string' ? value.trim().toLowerCase().replaceAll('_', '-') : '';
  const next: Locale = normalized === 'en' || normalized.startsWith('en-') ? 'en' : 'zh-CN';
  if (next === locale) return false;
  locale = next; return true;
}
/** Runtime marker boundary; handwritten calls use the typed t() wrapper. */
export function format(key: MessageKey, params: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (slot, name: string) => String(params[name] ?? slot));
}
export function t<K extends MessageKey>(key: K, ...args: TranslationArgs<K>): string {
  return format(key, args[0]);
}
export class LocalizedError<K extends MessageKey = MessageKey> extends Error {
  readonly localize: () => string;
  constructor(key: K, ...args: TranslationArgs<K>) {
    super(t(key, ...args)); this.localize = () => t(key, ...args);
  }
}

const sendingKeys = ['sendNoPermission', 'sendDisabled', 'sendNoPrompt', 'sendNoControl', 'sendUnbound'] as const;
/** Exact known backend reasons only; unknown diagnostics remain verbatim. */
function sendingKey(raw: string) {
  return sendingKeys.find(key => raw === messages.en[key] || raw === messages['zh-CN'][key]);
}
export function sendingReason(raw: string): string {
  const key = sendingKey(raw); return key ? t(key) : raw;
}
export function sendingError(raw: string): Error {
  const key = sendingKey(raw); return key ? new LocalizedError(key) : new Error(raw);
}
export function sessionLabel(raw: string): string {
  if (!raw || raw === messages.en.unbound || raw === messages['zh-CN'].unbound) return t('unbound');
  for (const lang of ['en', 'zh-CN'] as const) {
    const prefix = messages[lang].boundSession.split('{suffix}')[0]!;
    if (raw.startsWith(prefix)) return t('boundSession', { suffix: raw.slice(prefix.length) });
  }
  return raw;
}
